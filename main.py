import threading

from pydantic import BaseModel

from panoptic.core.databases.data.models import Property
from panoptic.core.plugin.plugin import APlugin
from panoptic.models.action_models import ActionContext, ActionResult, Notif, NotifType

from .engines import Detail, DescribeEngine, Engine, make_engine
from .task import DescribeTask


class PluginParams(BaseModel):
    """
    @prop_name: name of the text property that receives the descriptions
    @engine: florence2 (default, fast, CPU friendly, English) or vlm (Qwen3.5, follows the prompt in any language, GPU recommended)
    @detail: length of the florence2 descriptions
    @prompt: instruction sent to the vlm model, e.g. to describe in French or list the objects
    @max_tokens: maximum length of the text generated by the vlm model
    @max_image_size: longest side in px of the images sent to the model, 0 to keep the original size
    @florence_model: Hugging Face model used by the florence2 engine
    @vlm_model: Hugging Face image-text-to-text model used by the vlm engine
    """
    prop_name: str = 'description'
    engine: Engine = Engine.florence2
    detail: Detail = Detail.detailed
    prompt: str = 'Describe this image in one or two sentences.'
    max_tokens: int = 256
    max_image_size: int = 1024
    florence_model: str = 'florence-community/Florence-2-base'
    vlm_model: str = 'Qwen/Qwen3.5-2B'


ENGINE_PARAMS = {
    Engine.florence2: ('florence_model', 'detail'),
    Engine.vlm: ('vlm_model', 'prompt', 'max_tokens'),
}


class DescribePlugin(APlugin):
    """
    Describes the content of images in natural language and stores it in a text property.
    """

    def __init__(self, name: str, project, plugin_path: str):
        super().__init__(name=name, project=project, plugin_path=plugin_path)
        self.params = PluginParams()
        self._engine: DescribeEngine | None = None
        self._engine_key = None
        self._engine_lock = threading.Lock()
        self.add_action_easy(self.describe, ['execute'])

    def update_params(self, params) -> PluginParams:
        # validated, unlike APlugin.update_params, so ints and enums keep their types
        update = params if isinstance(params, dict) else params.model_dump()
        self.params = PluginParams(**{**self.params.model_dump(), **update})
        self.project.save_params(self.params.model_dump(mode='json'))
        return self.params

    def _stop(self) -> None:
        with self._engine_lock:
            self._close_engine()

    def describe(self, context: ActionContext, overwrite: bool = False) -> ActionResult:
        """Describe the selected images (the whole project when nothing is selected) in the description property.
        @overwrite: also process the images that already have a description
        """
        sha1s = self._get_sha1s(context)
        if not sha1s:
            return ActionResult(notifs=[Notif(NotifType.WARNING, name='describe', message='No image selected')])
        prop = self._get_property()
        if not overwrite:
            done = {v.sha1 for v in self.project.get_sha1_values(property_id=prop.id, sha1=sha1s) if v.value}
            sha1s = [s for s in sha1s if s not in done]
        if not sha1s:
            return ActionResult(notifs=[Notif(
                NotifType.INFO, name='describe', message='All the selected images already have a description',
            )])
        task = self.project.add_task(DescribeTask(self, sha1s, prop.id))
        return ActionResult(task_id=task.id if task else None, notifs=[Notif(
            NotifType.INFO, name='describe', message=f'Description started on {len(sha1s)} images',
        )])

    def get_engine(self) -> DescribeEngine:
        """The engine for the current params, reloaded when they change."""
        engine = Engine(self.params.engine)
        key = (engine, *(getattr(self.params, p) for p in ENGINE_PARAMS[engine]))
        with self._engine_lock:
            if self._engine is None or self._engine_key != key:
                self._close_engine()
                self._engine = make_engine(self.params)
                self._engine_key = key
            return self._engine

    def _close_engine(self) -> None:
        if self._engine is not None:
            self._engine.close()
        self._engine = None
        self._engine_key = None

    def _get_property(self) -> Property:
        name = self.params.prop_name
        for prop in self.project.get_properties(name=name):
            if prop.dtype == 'text' and prop.mode == 'sha1':
                return prop
        return self.project.add_property(name, 'text', 'sha1')

    def _get_sha1s(self, context: ActionContext) -> list[str]:
        if context.instance_ids:
            instances = self.project.get_instances(id=context.instance_ids)
        else:
            instances = self.project.get_instances()
        return list(dict.fromkeys(i.sha1 for i in instances if i.sha1))
